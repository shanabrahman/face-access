BEGIN;

CREATE TABLE IF NOT EXISTS shifts (
    shift_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    start_time TEXT NOT NULL,
    end_time TEXT NOT NULL,
    grace_period_minutes INTEGER NOT NULL DEFAULT 15 CHECK (grace_period_minutes >= 0),
    on_time_window_minutes INTEGER NOT NULL DEFAULT 0 CHECK (on_time_window_minutes >= 0),
    standard_work_hours DOUBLE PRECISION NOT NULL DEFAULT 8 CHECK (standard_work_hours > 0),
    active INTEGER NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
    removed_at TEXT
);

CREATE TABLE IF NOT EXISTS employees (
    employee_id TEXT PRIMARY KEY,
    face_name TEXT NOT NULL UNIQUE,
    full_name TEXT NOT NULL,
    department TEXT NOT NULL DEFAULT '',
    designation TEXT NOT NULL DEFAULT '',
    email TEXT NOT NULL DEFAULT '',
    phone TEXT NOT NULL DEFAULT '',
    joining_date TEXT NOT NULL DEFAULT '',
    profile_photo TEXT NOT NULL DEFAULT '',
    shift_id BIGINT NOT NULL DEFAULT 1 REFERENCES shifts(shift_id),
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
    consent_at TEXT,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS attendance (
    attendance_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id TEXT NOT NULL REFERENCES employees(employee_id),
    shift_id BIGINT NOT NULL REFERENCES shifts(shift_id),
    attendance_date TEXT NOT NULL,
    check_in TEXT NOT NULL,
    check_out TEXT,
    working_hours DOUBLE PRECISION,
    late INTEGER NOT NULL DEFAULT 0 CHECK (late IN (0, 1)),
    late_after_grace INTEGER NOT NULL DEFAULT 0 CHECK (late_after_grace IN (0, 1)),
    early_departure INTEGER NOT NULL DEFAULT 0 CHECK (early_departure IN (0, 1)),
    checkin_photo_path TEXT,
    checkout_photo_path TEXT,
    checkin_photo_timestamp TEXT,
    checkout_photo_timestamp TEXT,
    checkin_recognition_score DOUBLE PRECISION,
    checkout_recognition_score DOUBLE PRECISION,
    checkin_liveness_score DOUBLE PRECISION,
    checkout_liveness_score DOUBLE PRECISION,
    status TEXT NOT NULL DEFAULT 'present' CHECK (status IN ('present', 'checked_out')),
    missing_checkout_pending INTEGER NOT NULL DEFAULT 0 CHECK (missing_checkout_pending IN (0, 1)),
    UNIQUE (employee_id, attendance_date, shift_id)
);

CREATE TABLE IF NOT EXISTS attendance_movements (
    movement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attendance_id BIGINT NOT NULL REFERENCES attendance(attendance_id) ON DELETE CASCADE,
    action TEXT NOT NULL CHECK (action IN ('check_in', 'check_out')),
    occurred_at TEXT NOT NULL,
    photo_path TEXT,
    recognition_score DOUBLE PRECISION,
    liveness_score DOUBLE PRECISION
);

CREATE TABLE IF NOT EXISTS access_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_key TEXT UNIQUE,
    time TEXT NOT NULL,
    event TEXT NOT NULL,
    status TEXT NOT NULL,
    name TEXT NOT NULL,
    score TEXT NOT NULL DEFAULT '',
    method TEXT NOT NULL DEFAULT '',
    details TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS leave_requests (
    leave_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id TEXT NOT NULL REFERENCES employees(employee_id),
    start_date TEXT NOT NULL,
    end_date TEXT NOT NULL,
    reason TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
    created_at TEXT NOT NULL,
    reviewed_at TEXT
);

CREATE TABLE IF NOT EXISTS employee_accounts (
    employee_id TEXT PRIMARY KEY REFERENCES employees(employee_id) ON DELETE CASCADE,
    password_salt TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    is_active INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    annual_leave_days DOUBLE PRECISION CHECK (annual_leave_days >= 0),
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    last_login_at TEXT
);

CREATE TABLE IF NOT EXISTS hod_accounts (
    hod_id TEXT PRIMARY KEY,
    full_name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    department TEXT NOT NULL,
    password_salt TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    is_active INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    last_login_at TEXT
);

CREATE TABLE IF NOT EXISTS attendance_correction_requests (
    correction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id TEXT NOT NULL REFERENCES employees(employee_id),
    attendance_date TEXT NOT NULL,
    requested_check_in TEXT,
    requested_check_out TEXT,
    reason TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
    created_at TEXT NOT NULL,
    reviewed_at TEXT,
    reviewer_note TEXT NOT NULL DEFAULT '',
    request_type TEXT NOT NULL DEFAULT 'Forgot to checkout',
    supporting_document TEXT NOT NULL DEFAULT '',
    original_check_in TEXT,
    original_check_out TEXT,
    approved_check_out TEXT,
    approver_id TEXT NOT NULL DEFAULT '',
    approver_name TEXT NOT NULL DEFAULT '',
    approver_role TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS attendance_correction_audit (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correction_id BIGINT NOT NULL REFERENCES attendance_correction_requests(correction_id) ON DELETE CASCADE,
    action TEXT NOT NULL,
    actor_id TEXT NOT NULL DEFAULT '',
    actor_name TEXT NOT NULL DEFAULT '',
    actor_role TEXT NOT NULL DEFAULT '',
    details TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS daily_attendance_summary (
    summary_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id TEXT NOT NULL REFERENCES employees(employee_id),
    attendance_date TEXT NOT NULL,
    first_check_in TEXT,
    final_checkout TEXT,
    working_hours DOUBLE PRECISION,
    break_duration DOUBLE PRECISION NOT NULL DEFAULT 0,
    offsite_duration DOUBLE PRECISION NOT NULL DEFAULT 0,
    attendance_status TEXT NOT NULL,
    punctuality_status TEXT NOT NULL DEFAULT 'NOT_CHECKED_IN',
    checkout_verification_status TEXT NOT NULL DEFAULT 'pending',
    correction_approval_status TEXT NOT NULL DEFAULT 'none',
    early_departure_minutes INTEGER NOT NULL DEFAULT 0,
    late_minutes INTEGER NOT NULL DEFAULT 0,
    last_reconciled_at TEXT NOT NULL,
    UNIQUE (employee_id, attendance_date)
);

CREATE TABLE IF NOT EXISTS offsite_meeting_records (
    meeting_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id TEXT NOT NULL REFERENCES employees(employee_id),
    attendance_date TEXT NOT NULL,
    departure_time TEXT NOT NULL,
    return_time TEXT,
    meeting_title TEXT NOT NULL,
    meeting_details TEXT NOT NULL DEFAULT '',
    location TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
    duration_hours DOUBLE PRECISION,
    submitted_at TEXT NOT NULL,
    reviewed_at TEXT,
    reviewer_id TEXT NOT NULL DEFAULT '',
    reviewer_name TEXT NOT NULL DEFAULT '',
    reviewer_role TEXT NOT NULL DEFAULT '',
    reviewer_note TEXT NOT NULL DEFAULT '',
    UNIQUE (employee_id, attendance_date, departure_time)
);

CREATE TABLE IF NOT EXISTS app_notifications (
    notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_role TEXT NOT NULL,
    recipient_id TEXT NOT NULL DEFAULT '',
    employee_id TEXT NOT NULL DEFAULT '',
    category TEXT NOT NULL,
    title TEXT NOT NULL,
    message TEXT NOT NULL,
    is_read INTEGER NOT NULL DEFAULT 0 CHECK (is_read IN (0, 1)),
    created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS app_settings (
    setting_key TEXT PRIMARY KEY,
    setting_value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS schema_migrations (
    version INTEGER PRIMARY KEY,
    applied_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS chatbot_messages (
    message_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_key TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('user', 'assistant')),
    content TEXT NOT NULL,
    photos_json TEXT NOT NULL DEFAULT '[]',
    created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS chatbot_context (
    session_key TEXT PRIMARY KEY,
    context_json TEXT NOT NULL,
    updated_at TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_hod_department ON hod_accounts(department);
CREATE INDEX IF NOT EXISTS idx_corrections_employee_date ON attendance_correction_requests(employee_id, attendance_date);
CREATE UNIQUE INDEX IF NOT EXISTS idx_corrections_active_unique ON attendance_correction_requests(employee_id, attendance_date) WHERE status IN ('pending', 'approved');
CREATE INDEX IF NOT EXISTS idx_daily_summary_date_department ON daily_attendance_summary(attendance_date, employee_id);
CREATE INDEX IF NOT EXISTS idx_notifications_recipient ON app_notifications(recipient_role, recipient_id, is_read);
CREATE INDEX IF NOT EXISTS idx_chatbot_messages_session ON chatbot_messages(session_key, message_id);
CREATE INDEX IF NOT EXISTS idx_attendance_date ON attendance(attendance_date);
CREATE INDEX IF NOT EXISTS idx_attendance_employee_date ON attendance(employee_id, attendance_date);
CREATE INDEX IF NOT EXISTS idx_access_time ON access_events(time);

